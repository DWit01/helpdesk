from datetime import UTC, datetime
from enum import Enum
from typing import TYPE_CHECKING
from uuid import UUID, uuid4

from sqlalchemy import DateTime, String
from sqlalchemy import Enum as SQLEnum
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.comment import Comment
    from app.models.ticket import Ticket


# Define the permitted Helpdesk user roles
class UserRole(str, Enum):
    REQUESTER = "requester"
    AGENT = "agent"
    ADMIN = "admin"


class User(Base):
    __tablename__ = "users"

    # UUID primary key generated by the application
    id: Mapped[UUID] = mapped_column(
        primary_key=True,
        default=uuid4,
    )

    keycloak_sub: Mapped[str] = mapped_column(
        String(255),
        unique=True,
    )

    username: Mapped[str] = mapped_column(String(50))
    email: Mapped[str] = mapped_column(String(255))
    full_name: Mapped[str | None] = mapped_column(String(255))

    is_active: Mapped[bool] = mapped_column(default=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        onupdate=lambda: datetime.now(UTC),
    )

    # Store lowercase role values and enforce permitted values
    role: Mapped[UserRole] = mapped_column(
        SQLEnum(
            UserRole,
            values_callable=lambda user_role: [role.value for role in user_role],
            create_constraint=True,
            name="user_role",
        )
    )

    # Separate relationships because tickets reference users twice
    requested_tickets: Mapped[list["Ticket"]] = relationship(
        "Ticket",
        back_populates="requester",
        foreign_keys="Ticket.requester_id",
    )

    assigned_tickets: Mapped[list["Ticket"]] = relationship(
        "Ticket",
        back_populates="assignee",
        foreign_keys="Ticket.assignee_id",
    )

    comments: Mapped[list["Comment"]] = relationship(
        "Comment",
        back_populates="author",
    )
